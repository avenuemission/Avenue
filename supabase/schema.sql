-- ============================================================
-- Avenue Website — Supabase Schema
-- Run this in the Supabase SQL Editor (Dashboard > SQL Editor)
-- WARNING: This script DROPS existing tables and recreates them
-- from scratch, so all data is reset. Use only for clean setup.
-- ============================================================

-- Drop existing tables in reverse dependency order
-- (disable triggers to avoid foreign-key conflicts during cleanup)
set session_replication_role = 'replica';
drop table if exists public.intersection_event_dates cascade;
drop table if exists public.intersection_events cascade;
drop table if exists public.form_submissions cascade;
drop table if exists public.pathway_groups cascade;
drop table if exists public.study_guides cascade;
drop table if exists public.site_stats cascade;
drop table if exists public.leaders cascade;
set session_replication_role = 'origin';

-- Required for gen_random_uuid()
create extension if not exists "pgcrypto";

-- ------------------------------------------------------------
-- 1. FORM SUBMISSIONS (unified table for all website forms)
--    form_type: 'start-pathway' | 'join-pathway' | 'mission-support'
--               | 'idea-submission' | 'leader-support'
--    data: flexible JSON payload of all extra fields
-- ------------------------------------------------------------
create table if not exists public.form_submissions (
  id          uuid primary key default gen_random_uuid(),
  form_type   text not null,
  name        text,
  email       text,
  data        jsonb not null default '{}'::jsonb,
  archived    boolean not null default false,
  created_at  timestamptz not null default now()
);
create index if not exists form_submissions_type_idx on public.form_submissions (form_type);
create index if not exists form_submissions_created_idx on public.form_submissions (created_at desc);

-- ------------------------------------------------------------
-- 2. PATHWAY GROUPS (map + pathways page)
-- ------------------------------------------------------------
create table if not exists public.pathway_groups (
  id          bigint generated by default as identity primary key,
  name        text not null,
  latitude    double precision not null,
  longitude   double precision not null,
  time        text,
  coordinator text,
  phone       text,
  running     boolean not null default false,
  description text,
  sort_order  int not null default 0,
  created_at  timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 3. INTERSECTION EVENTS (info cards)
-- ------------------------------------------------------------
create table if not exists public.intersection_events (
  key         text primary key,           -- prayerAndPraise | weekOfWorship | quarterlySermon
  title       text not null,
  description text,
  location    text,
  time        text,
  sort_order  int not null default 0
);

-- ------------------------------------------------------------
-- 4. INTERSECTION EVENT DATES (upcoming dates per event)
-- ------------------------------------------------------------
create table if not exists public.intersection_event_dates (
  id          uuid primary key default gen_random_uuid(),
  event_key   text not null references public.intersection_events(key) on delete cascade,
  event_date  date not null,              -- the calendar date
  event_time  text not null default '19:00', -- HH:MM (Melbourne local)
  created_at  timestamptz not null default now()
);
create index if not exists event_dates_key_idx on public.intersection_event_dates (event_key, event_date);

-- Prevent duplicate event dates when re-running the schema
alter table public.intersection_event_dates
  drop constraint if exists unique_event_date,
  add constraint unique_event_date unique (event_key, event_date);

-- ------------------------------------------------------------
-- 5. STUDY GUIDES (Weekly Pathways Topics)
-- ------------------------------------------------------------
create table if not exists public.study_guides (
  id          uuid primary key default gen_random_uuid(),
  guide_date  text,                       -- display date e.g. 27/12/2025
  series      text,
  topic       text,
  scripture   text,                       -- the "text" column from CSV (e.g. James 1)
  spotify_url text,
  pdf_url     text,
  color       text,
  sort_order  int not null default 0,
  created_at  timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 6. SITE STATS (Pathways page counters, editable)
-- ------------------------------------------------------------
create table if not exists public.site_stats (
  key    text primary key,                -- communities | countries | languages | new_groups
  value  int not null default 0,
  label  text
);

-- ------------------------------------------------------------
-- 7. LEADERS (migrated from Netlify Blobs)
-- ------------------------------------------------------------
create table if not exists public.leaders (
  id           text primary key,
  email        text unique not null,
  name         text,
  full_access  boolean not null default false,
  created_at   timestamptz not null default now()
);

-- ============================================================
-- ROW LEVEL SECURITY
-- Public site uses the ANON key. Admin routes use the
-- SERVICE ROLE key (bypasses RLS entirely).
-- ============================================================
alter table public.form_submissions        enable row level security;
alter table public.pathway_groups          enable row level security;
alter table public.intersection_events     enable row level security;
alter table public.intersection_event_dates enable row level security;
alter table public.study_guides            enable row level security;
alter table public.site_stats              enable row level security;
alter table public.leaders                 enable row level security;

-- Public can READ content tables (needed to render the site with anon key)
drop policy if exists "public read pathway_groups" on public.pathway_groups;
create policy "public read pathway_groups" on public.pathway_groups for select using (true);

drop policy if exists "public read intersection_events" on public.intersection_events;
create policy "public read intersection_events" on public.intersection_events for select using (true);

drop policy if exists "public read event_dates" on public.intersection_event_dates;
create policy "public read event_dates" on public.intersection_event_dates for select using (true);

drop policy if exists "public read study_guides" on public.study_guides;
create policy "public read study_guides" on public.study_guides for select using (true);

drop policy if exists "public read site_stats" on public.site_stats;
create policy "public read site_stats" on public.site_stats for select using (true);

-- Public can INSERT form submissions (so website forms work with anon key)
-- but CANNOT read them back (privacy). Admin reads via service role.
drop policy if exists "public insert submissions" on public.form_submissions;
create policy "public insert submissions" on public.form_submissions for insert with check (true);

-- NOTE: no public policies on public.leaders — only the service role
-- (admin API routes) can read/write it.

